#!/usr/bin/env bash
#
# mayhem/build.sh — build magma's access-gateway NAS codecs (4G EMM/ESM, 5G 5GMM/5GSM) and
# their fuzz harnesses, plus the known-answer suite mayhem/test.sh runs.
#
# Upstream's build is Bazel over the whole MME (ITTI, czmq, freeDiameter, gRPC, folly, asn1c
# NGAP/S1AP). The NAS message codecs are self-contained C/C++ (TLV codec, bstrlib, 3GPP IEs),
# so this compiles exactly those upstream sources, unmodified, with the fuzz flags. Two
# stand-ins live in mayhem/: log_stub.c (the shared logger needs the ITTI stack) and
# mayhem/shim/ (type names from liblfds710.h; an empty amf_app_defs.hpp, which the 5G
# codec files include but do not use), and the GTPv2-C message parser
# (lib/gtpv2-c/nwgtpv2c-0.11, headers need czmq.h from apt libczmq-dev) with the S11 IE
# decoders the MME runs on its output (gtpv2c_ie_formatter.c, tasks/s11/s11_ie_formatter.cpp), and
# the NAS PDU entry nas_message_decode with lib/secu (nettle 2.5 from /opt/toolchains/deps, apt libssl-dev),
# and the S1AP/NGAP APER decoders generated by upstream's asn1c fork (/opt/toolchains/deps). Outputs:
#   /mayhem/fuzz_<t>, /mayhem/fuzz_<t>-standalone   (ASan+UBSan, DWARF 3)
#   mayhem/build/nas_kat                             (normal flags; run by mayhem/test.sh)
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"
O=lte/gateway/c/core/oai
B="$SRC/mayhem/build"          # gitignored (mayhem/.gitignore)
mkdir -p "$B"

: "${NETTLE:=/opt/toolchains/deps/nettle-2.5}"
INC4=(-I"$SRC/mayhem/shim" -I"$SRC" -I"$SRC/orc8r/gateway/c/common/logging" -I"$NETTLE/include")
# 5G codec: the shim must win over the repo root for amf_app_defs.hpp.
INC5=("${INC4[@]}")
WARN=(-w)

C_SRCS=( $O/lib/3gpp/*.c $O/common/TLVDecoder.c $O/common/TLVEncoder.c
         $O/lib/bstr/bstrlib.c lte/gateway/c/core/common/backtrace.c mayhem/log_stub.c
         $O/lib/gtpv2-c/nwgtpv2c-0.11/src/NwGtpv2cMsg.c
         $O/lib/gtpv2-c/nwgtpv2c-0.11/src/NwGtpv2cMsgParser.c
         $O/lib/gtpv2-c/nwgtpv2c-0.11/src/NwGtpv2cMsgIeParseInfo.c
         $O/lib/secu/nas_stream_eea1.c $O/lib/secu/nas_stream_eea2.c
         $O/lib/secu/nas_stream_eia1.c $O/lib/secu/nas_stream_eia2.c
         $O/lib/secu/snow3g.c $O/lib/secu/rijndael.c )
CXX4_SRCS=( $O/tasks/nas/emm/msg/*.cpp $O/tasks/nas/esm/msg/*.cpp $O/tasks/nas/ies/*.cpp
            lte/gateway/c/core/common/dynamic_memory_check.cpp mayhem/nas5g_log_names.cpp
            $O/tasks/nas/api/network/nas_message.cpp )
CXX5_SRCS=( $O/tasks/nas5g/src/*.cpp $O/tasks/nas5g/src/ies/*.cpp )

# compile_lib <outdir> <libname> <cflags...> -- compiles the codec sources into <outdir>/<lib>.a
compile_lib() {
  local out="$1" name="$2"; shift 2
  local flags="$*"
  mkdir -p "$out/obj"
  local list="$out/srcs.txt"
  : > "$list"
  for s in "${C_SRCS[@]}"; do echo "c $s" >> "$list"; done
  for s in "${CXX4_SRCS[@]}" "${CXX5_SRCS[@]}"; do echo "cxx $s" >> "$list"; done
  export _FLAGS="$flags" _OUT="$out/obj" _INC="${INC5[*]}"
  xargs -P "$MAYHEM_JOBS" -L1 bash -c '
    set -e
    kind="$0"; s="$1"; o="$_OUT/$(echo "$s" | tr / _).o"
    if [ "$kind" = c ]; then $CC -std=gnu11 -w $_FLAGS $_INC -c "$s" -o "$o"
    else $CXX -std=c++14 -w $_FLAGS $_INC -c "$s" -o "$o"; fi' < "$list"
  rm -f "$out/$name.a"
  ar rcs "$out/$name.a" "$out"/obj/*.o
}

# S1AP / NGAP: generate the asn1c code from upstream's ASN.1 exactly as bazel/asn1c.bzl does
# (upstream's asn1c fork at ebed802, /opt/toolchains/deps; same flags, prefix and
# substitution), then build it with the decoder entry point into its own archive.
ASN1C=/opt/toolchains/deps/asn1c-ebed802/bin/asn1c
gen_asn1() {  # <outdir> <asn1 file> <prefix>
  local out="$1" asn="$2" pfx="$3"
  rm -rf "$out"; mkdir -p "$out"
  ASN1C_PREFIX="$pfx" "$ASN1C" -pdu=all -fcompound-names -fno-include-deps -no-gen-example \
      -D "$out" "$asn" > "$out.log" 2>&1
  find "$out" -maxdepth 1 -type f ! -name '*.c' ! -name '*.h' -delete
  grep -lRZ '18446744073709551615' "$out" | xargs --no-run-if-empty -0 \
      sed -i -e 's/18446744073709551615/18446744073709551615u/g'
}
# asn_lib <name> <gen dir> <decoder source> <cflags...>
asn_lib() {
  local name="$1" gdir="$2" dec="$3"; shift 3
  local flags="$*"
  local odir="$gdir.obj"
  rm -rf "$odir"; mkdir -p "$odir"
  # asn1c's ASN__STACK_OVERFLOW_CHECK compares the addresses of locals; under ASan's
  # fake stack (use-after-return detection) they are heap addresses, so every decode
  # "overflows" and returns RC_FAIL. Keep real stack frames for the generated code only.
  local uar=""
  case "$flags" in *-fsanitize=*address*) uar="-fsanitize-address-use-after-return=never" ;; esac
  # The asn1c runtime skeleton computes `buf + 0` with buf == NULL on its first chunk
  # (aper_opentype.c) and left-shifts a negative sentinel (OPEN_TYPE_aper.c); both are
  # benign and hit on nearly every open-type decode, so UBSan would halt before any
  # message is parsed. Relax only those two checks, only for the generated code.
  case "$flags" in *-fsanitize=*undefined*) uar="$uar -fno-sanitize=pointer-overflow,shift-base" ;; esac
  export _FLAGS="$flags $uar" _OUT="$odir" _GDIR="$gdir"
  ls "$gdir"/*.c | xargs -P "$MAYHEM_JOBS" -I{} bash -c \
      '$CC -std=gnu11 -w $_FLAGS -I"$_GDIR" -c "{}" -o "$_OUT/$(basename "{}").o"'
  case "$dec" in
    *.c)   $CC  -std=gnu11 -w $flags -I"$gdir" -I"$B/asn1/s1ap" "${INC4[@]}" -I"$B/protos" -c "$dec" -o "$odir/decoder.o" ;;
    *.cpp) $CXX -std=c++17 -w $flags -I"$gdir" "${INC4[@]}" -I"$B/protos" -c "$dec" -o "$odir/decoder.o" ;;
  esac
  rm -f "$B/$name.a"; ar rcs "$B/$name.a" "$odir"/*.o
}
# GTPv2-C S11 IE decoders (the gtpv2c_*_ie_get callbacks the MME's S11 handlers register):
# their headers (sgw_ie_defs.h, s11_messages_types.hpp) name S1AP and NGAP asn1c types, so
# they build against the generated headers, apart from the NAS codec library.
s11ie_lib() {  # <outdir> <cflags...>
  local out="$1"; shift
  local flags="$*"
  local inc=(-I"$B/asn1/ngap" -I"$B/asn1/s1ap" -I"$B/protos" "${INC4[@]}")
  rm -rf "$out"; mkdir -p "$out"
  $CC  -std=gnu11 -w $flags "${inc[@]}" -c $O/lib/gtpv2-c/gtpv2c_ie_formatter/src/gtpv2c_ie_formatter.c -o "$out/gtpv2c_ie_formatter.o"
  $CC  -std=gnu11 -w $flags "${inc[@]}" -c $O/lib/message_utils/ie_to_bytes.c -o "$out/ie_to_bytes.o"
  $CXX -std=c++14 -w $flags "${inc[@]}" -c $O/tasks/s11/s11_ie_formatter.cpp -o "$out/s11_ie_formatter.o"
  ar rcs "$out/libs11ie.a" "$out"/*.o
}
# The S1AP decoder's header chain (s1ap_common.hpp -> s1ap_state.hpp) names the MME state
# protobuf types: generate those headers with apt protoc (nothing here links protobuf).
rm -rf "$B/protos"; mkdir -p "$B/protos"
protoc -I"$SRC" --cpp_out="$B/protos" lte/protos/oai/*.proto
gen_asn1 "$B/asn1/s1ap" $O/tasks/s1ap/messages/asn1/r15/s1ap-15.6.0.asn1 S1ap_
gen_asn1 "$B/asn1/ngap" $O/tasks/ngap/messages/asn1/r16/r16.asn1 Ngap_

# 1) the codecs with the fuzz flags (project code instrumented, DWARF 3)
FUZZ_FLAGS="$SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link"
compile_lib "$B/fuzz" libnascodec $FUZZ_FLAGS
asn_lib libs1ap_fuzz "$B/asn1/s1ap" $O/tasks/s1ap/s1ap_mme_decoder.cpp $FUZZ_FLAGS
asn_lib libngap_fuzz "$B/asn1/ngap" $O/tasks/ngap/ngap_amf_decoder.c $FUZZ_FLAGS
s11ie_lib "$B/s11ie" $FUZZ_FLAGS

$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.cc -o "$B/lsan_off.o"
$CC  $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"

# 2) the harnesses, each twice: libFuzzer binary + run-once standalone reproducer
# NAS EEA2 uses nettle 2.5 (static, /opt/toolchains/deps, built by the Dockerfile) and EIA2
# uses apt OpenSSL; both stay uninstrumented.
SYSLIBS=("$NETTLE/lib/libnettle.a" -lcrypto)
for t in fuzz_emm_msg fuzz_esm_msg fuzz_nas5g_amf fuzz_nas5g_smf fuzz_gtpv2c_msg fuzz_nas_message \
         fuzz_s1ap_pdu fuzz_ngap_pdu; do
  EXTRA_INC=() ; EXTRA_LIB=()
  case "$t" in
    fuzz_s1ap_pdu) EXTRA_INC=(-I"$B/asn1/s1ap" -I"$B/protos"); EXTRA_LIB=("$B/libs1ap_fuzz.a") ;;
    # ngap headers first; 3gpp_36.413.h also names an S1AP cause type
    fuzz_ngap_pdu) EXTRA_INC=(-I"$B/asn1/ngap" -I"$B/asn1/s1ap"); EXTRA_LIB=("$B/libngap_fuzz.a") ;;
    fuzz_gtpv2c_msg) EXTRA_INC=(-I"$B/asn1/ngap" -I"$B/asn1/s1ap" -I"$B/protos"); EXTRA_LIB=("$B/s11ie/libs11ie.a") ;;
  esac
  if [ -f "mayhem/harnesses/$t.c" ]; then
    $CC -std=gnu11 -w $SANITIZER_FLAGS $DEBUG_FLAGS "${EXTRA_INC[@]}" "${INC5[@]}" -c "mayhem/harnesses/$t.c" -o "$B/$t.o"
  else
    $CXX -std=c++17 -w $SANITIZER_FLAGS $DEBUG_FLAGS "${EXTRA_INC[@]}" "${INC5[@]}" -c "mayhem/harnesses/$t.cpp" -o "$B/$t.o"
  fi
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$B/$t.o" "$B/lsan_off.o" \
       "${EXTRA_LIB[@]}" "$B/fuzz/libnascodec.a" "${SYSLIBS[@]}" -o "$SRC/$t"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$B/standalone_main.o" "$B/$t.o" "$B/lsan_off.o" \
       "${EXTRA_LIB[@]}" "$B/fuzz/libnascodec.a" "${SYSLIBS[@]}" -o "$SRC/$t-standalone"
done

# 3) the known-answer suite with NORMAL flags (independent build of the same codec sources)
TEST_FLAGS="-O1 -g $COVERAGE_FLAGS"
compile_lib "$B/test" libnascodec $TEST_FLAGS
$CXX -std=c++14 -w $TEST_FLAGS "${INC5[@]}" mayhem/nas_kat.cpp "$B/test/libnascodec.a" "${SYSLIBS[@]}" -o "$B/nas_kat"
echo "build.sh: done"
